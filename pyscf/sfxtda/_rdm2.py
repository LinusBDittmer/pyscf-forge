'''
Effective two-body density of an SF-XTDA vector, contracted with a symmetric 3-index tensor.

Every _blocks.py formula is linear in the integrals [pq|rs], so x.(H - E0)^{2e}.x = sum Gamma_pqrs [pq|rs].
For a symmetric F (K, nmo, nmo)

    Y[F]^K_pq = sum_rs Gamma_pqrs F^K_rs        (symmetrised in pq)
    sum_K <Y[F]^K, F^K> = x.(H - E0).x   with [pq|rs] = sum_K F^K_pq F^K_rs and Fbar = 0,

so for the signed stacked fits of _DFInts, omega - tr(P Fbar) = sum_L s_L <Y[B]^L, B^L>.

TWO_BODY is generated by probing: each BLOCKS formula is evaluated with one integral argument = 1, all
other integral and Fock arguments = 0, and the deltas in {0, 1}; the result is decomposed as
c00 + c_ij delta_ij + c_ab delta_ab + c_ijab delta_ij delta_ab.  An entry (c, '(pq|rs)', deltas) between a
bra block u of type A and a ket block v of type B adds, with w = 1 for the same block and 2 otherwise
(BLOCKS holds each unordered pair once),

    Y[:, p, q] += (w c / 2) sum u v delta F[:, r, s],   Y[:, r, s] += (w c / 2) sum u v delta F[:, p, q].
'''

import itertools
import numpy
from pyscf.sfxtda._blocks import BLOCKS
from pyscf.sfxtda._tdm import _BRA, _KET
from pyscf.sfxtda.sfxtda import _labels

_DELTAS = ('delta_ij', 'delta_ab')


def _probe(args, f):
    '''Coefficients [(c, '(pq|rs)', deltas)] of the integral arguments of one BLOCKS formula.'''
    present = [d for d in _DELTAS if d in args]
    out = []
    for name in args:
        if not name.startswith('('):
            continue
        vals = {}
        for ds in itertools.product((0, 1), repeat=len(present)):
            env = dict(zip(present, ds))
            x0 = [env.get(a, 0) for a in args]
            x1 = [1 if a == name else env.get(a, 0) for a in args]
            vals[ds] = f(*x1) - f(*x0)
        # multilinear decomposition (inclusion-exclusion over the present deltas)
        for sub in itertools.product((0, 1), repeat=len(present)):
            c = sum((-1) ** (sum(sub) - sum(ds)) * v for ds, v in vals.items()
                    if all(d <= s for d, s in zip(ds, sub)))
            if abs(c) > 1e-14:
                deltas = ''.join(d[-2:] for d, s in zip(present, sub) if s)
                out.append((float(c), name, deltas))
    return out


TWO_BODY = {key: t for key, v in BLOCKS.items() if (t := _probe(*v))}


def contract(x, blocks, f, core, somo, virt):
    '''Y[f] (K, nmo, nmo) of the CSF vector x (blocks = csf_list(spin, nC, nV)) for symmetric f (K, nmo, nmo).'''
    nC, nV = len(core), len(virt)
    orb = {'i': core, 'j': core, 'a': virt, 'b': virt, 'O1': somo[:1], 'O2': somo[1:]}
    shape = {'OO': (), 'CO': (nC,), 'OV': (nV,), 'CV': (nC, nV)}
    off = numpy.cumsum([0] + [r * c for _, _, (r, c) in blocks])
    us = [x[off[k]:off[k+1]].reshape(shape[cl]) for k, (cl, _, _) in enumerate(blocks)]
    y = numpy.zeros_like(f)
    nk = f.shape[0]
    for p, (A, na, _) in enumerate(blocks):
        for q, (B, nb, _) in enumerate(blocks):
            terms = TWO_BODY.get((A, na, B, nb))
            if terms is None:
                continue
            w = 1 if p == q else 2
            for c, name, deltas in terms:
                ren = {'j': 'i'} if 'ij' in deltas else {}
                if 'ab' in deltas:
                    ren['b'] = 'a'
                ket = ''.join(ren.get(k, k) for k in _KET[B])
                left, right = name[1:-1].split('|')
                labs = _labels(left) + _labels(right)
                sub = [ren.get(lab, lab) if lab in 'ijab' else 'wxyz'[n] for n, lab in enumerate(labs)]
                for (r, s), (t, v) in (((0, 1), (2, 3)), ((2, 3), (0, 1))):
                    fs = f[:, orb[labs[t]][:, None], orb[labs[v]]]
                    out = ''.join(k for k in (sub[r], sub[s]) if k in 'ijab')
                    blk = numpy.einsum(f'{_BRA[A]},{ket},L{sub[t]}{sub[v]}->L{out}', us[p], us[q], fs,
                                       optimize=True)
                    y[:, orb[labs[r]][:, None], orb[labs[s]]] += (.5 * w * c) * blk.reshape(
                        nk, len(orb[labs[r]]), len(orb[labs[s]]))
    return .5 * (y + y.transpose(0, 2, 1))
